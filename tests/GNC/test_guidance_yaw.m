function info = test_guidance_yaw()
%TEST_GUIDANCE_YAW 动态 yaw/yaw_rate 从 Guidance 经 Position/Velocity 传到 Attitude

source = struct('type', 'fixture', 'tables', shc09_aero_fixture());
scenario = hover_scenario(struct( ...
    'aero_source', source, ...
    'tspan', [0, 0.4], ...
    'yaw', 0.2, ...
    'yaw_rate', 0.15, ...
    'max_records', 20000));
result = aero_sim(scenario.model, scenario.cfg);

records = result.communication.log.records;
names = cellfun(@(r) r.name, records, 'UniformOutput', false);
velocity = records(strcmp(names, 'control/velocity_setpoint'));
attitude = records(strcmp(names, 'control/attitude_setpoint'));
rate = records(strcmp(names, 'control/rate_setpoint'));
check_that(~isempty(velocity) && ~isempty(attitude) && ~isempty(rate), ...
    '缺少 yaw 传递链 Topic');

check_that(all(cellfun(@(r) abs(r.data.yaw - 0.2) < 1e-12, velocity)), ...
    'Velocity 设定未携带 Guidance yaw');
check_that(all(cellfun(@(r) abs(r.data.yaw_rate - 0.15) < 1e-12, velocity)), ...
    'Velocity 设定未携带 Guidance yaw_rate');
check_that(all(cellfun(@(r) abs(r.data.yaw - 0.2) < 1e-12, attitude)), ...
    'Attitude 设定未携带 yaw');
check_that(all(cellfun(@(r) abs(r.data.yaw_rate - 0.15) < 1e-12, attitude)), ...
    'Attitude 设定未携带 yaw_rate');

late = cellfun(@(r) r.sample_time_s > 0.1, rate);
lateOmega = cellfun(@(r) r.data.omega(3), rate(late));
check_that(~isempty(lateOmega) && all(lateOmega > 0.05), ...
    'yaw_rate 未进入 Rate 角速度参考');
check_that(max(abs(lateOmega)) <= scenario.gains.attitude.rate_limit(3) + 1e-12, ...
    'Rate 角速度参考超过姿态环限幅');
check_that(~any(cellfun(@(r) any(~isfinite(r.data.omega)), rate)), ...
    'Rate 参考含非有限值');

info = struct('passed', true, 'summary', sprintf( ...
    'yaw=0.2、yaw_rate=0.15 经 Position→Velocity→Attitude 传递；%d 个 rate 样本', ...
    numel(rate)));

end
