function info = test_pinv_allocator()
%TEST_PINV_ALLOCATOR 六舵面 PINV 分配：配平、力矩、限幅与残差

p = shc09_parameters();
trim = shc09_hover_equilibrium(p);
geometry = shc09_control_surface_geometry(p);
bus = make_bus(trim);
params = allocation_params(p, trim, geometry);

% 零力矩 → 精确回到配平，电机与悬停转速一致
bus.topics.publish('control/attitude_setpoint', ...
    struct('quaternion', [1; 0; 0; 0], 'thrust_n', trim.thrust_n), 0, 0, 0, 'test');
bus.topics.publish('control/torque_setpoint', struct('torque', zeros(3, 1)), 0, 0, 0, 'test');
bus = pinv_allocator(0, bus, params);
check_that(max(abs(bus.command.servos - trim.delta_rad)) < 1e-12, ...
    '零力矩时未回到配平舵角');
check_that(abs(bus.command.motor - trim.omega_rad_s) < 1e-6, ...
    '悬停推力对应的电机转速错误');

% 已知力矩 → 增量力矩可复现
Btau = p.servo_torque_coefficient * trim.exit_speed_m_s^2 * ...
    diag([p.l1_m, p.l1_m, p.l2_m]) * geometry.B_M;
tau = [0.05; -0.03; 0.01];
bus.topics.publish('control/torque_setpoint', struct('torque', tau), 1, 1, 1, 'test');
bus = pinv_allocator(1, bus, params);
achievedControl = Btau * (bus.command.servos - trim.delta_rad * ones(6, 1));
check_that(norm(achievedControl - tau) < 1e-6, ...
    'PINV 未复现期望力矩：%.3e', norm(achievedControl - tau));

% 大扭矩 → 舵面限幅、残差与饱和方向正确
bigTau = [2.0; 0; 0];
bus.topics.publish('control/torque_setpoint', struct('torque', bigTau), 2, 2, 2, 'test');
bus = pinv_allocator(2, bus, params);
status = bus.topics.read('control/allocation_status', 2);
check_that(all(status.data.delta <= p.servo_effective_range_rad(2) + 1e-12), ...
    '舵面偏角超出上限');
check_that(all(status.data.delta >= p.servo_effective_range_rad(1) - 1e-12), ...
    '舵面偏角超出下限');
check_that(status.data.saturated(1) > 0, '正力矩饱和方向未标记');
check_that(abs(status.data.residual(1) - (bigTau(1) - achieved_control(Btau, status.data.delta, trim))) < 1e-9, ...
    '残差定义与预期不符');

info = struct('passed', true, 'summary', sprintf( ...
    '配平/力矩复现/限幅/残差通过；大扭矩残差 %.3f N·m', status.data.residual(1)));

end

% ===========================================================================
function bus = make_bus(trim)
bus = struct();
bus.command = trim.command;
bus.topics = aero_topic_bus();
specs = topic_specs();
for k = 1:numel(specs)
    bus.topics.register(specs{k}.name, specs{k}.spec);
end
end

function value = achieved_control(Btau, delta, trim)
value = Btau * (delta - trim.delta_rad * ones(6, 1));
end

function params = allocation_params(p, trim, geometry)
params = struct( ...
    'torque_topic', 'control/torque_setpoint', ...
    'attitude_topic', 'control/attitude_setpoint', ...
    'status_topic', 'control/allocation_status', ...
    'B_M', geometry.B_M, ...
    'l1_m', p.l1_m, 'l2_m', p.l2_m, ...
    'servo_torque_coefficient', p.servo_torque_coefficient, ...
    'trim_delta_rad', trim.delta_rad, ...
    'delta_limit', p.servo_effective_range_rad, ...
    'diffuser_ratio', p.diffuser_ratio, ...
    'air_density', p.air_density_kg_m3, ...
    'disc_area', p.disc_area_m2, ...
    'k_T0', p.duct.k_T0, ...
    'hover_thrust_n', trim.thrust_n, ...
    'max_thrust_n', p.duct.k_T0 * p.motor_device.omega_range_rad_s(2)^2, ...
    'motor_min_rad_s', p.motor_device.omega_range_rad_s(1), ...
    'motor_max_rad_s', p.motor_device.omega_range_rad_s(2), ...
    've_min_m_s', 1e-3, ...
    'saturation_tolerance', 1e-6);
end
