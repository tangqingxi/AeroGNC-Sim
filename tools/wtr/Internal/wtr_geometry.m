function geometry = wtr_geometry(p)
%WTR_GEOMETRY 生成 windtrace.geometry.v1 自包含 FRD 几何
%
% 只使用 SHC09 已冻结的装配几何（六舵面方位角、l1/l2、生效行程）构造
% 示意网格；不包含气动效能、实测铰链或第三方模型。Viewer 只按该几何
% 与飞行数据绘制，不回读源工程。

g = shc09_control_surface_geometry(p);
phi = g.phi_rad(:);

% ---- 机体盒体（FRD，z 向下） ----------------------------------------
box = [0.30, 0.30, 0.60];
cx = box(1) / 2; cy = box(2) / 2;
zTop = -0.20; zBottom = 0.40;
points = [ ...
    -cx, -cy, zTop; cx, -cy, zTop; cx, cy, zTop; -cx, cy, zTop; ...
    -cx, -cy, zBottom; cx, -cy, zBottom; cx, cy, zBottom; -cx, cy, zBottom];
triangles = [1 2 3; 1 3 4; 5 6 7; 5 7 8; 1 2 6; 1 6 5; ...
             2 3 7; 2 7 6; 3 4 8; 3 8 7; 4 1 5; 4 5 8] - 1;   % 0 基索引
faces = [3 * ones(size(triangles, 1), 1), triangles];       % VTK 单元格式：3,i,j,k
body = struct('points', points, 'faces', faces, 'part', zeros(8, 1));

% ---- 六舵面示意网格 ------------------------------------------------
vanes = cell(1, 6);
for k = 1:6
    center = g.position_m(:, k).';
    axisDirection = g.axis(:, k).';
    radial = [cos(phi(k)), sin(phi(k)), 0];
    zDirection = [0, 0, 1];
    corners = [ ...
        center - radial * 0.030 - zDirection * 0.040; ...
        center + radial * 0.030 - zDirection * 0.040; ...
        center + radial * 0.030 + zDirection * 0.040; ...
        center - radial * 0.030 + zDirection * 0.040];
    vanes{k} = struct( ...
        'points', corners, ...
        'faces', [3, 0, 1, 2; 3, 0, 2, 3], ...   % VTK 单元格式（0 基）
        'center', center, ...
        'axis', axisDirection);
end

signature = sprintf('SHC09|%s|%s|%s', mat2str(box, 6), ...
    mat2str(g.position_m, 8), mat2str(p.servo_effective_range_rad, 8));

geometry = struct();
geometry.schema = 'windtrace.geometry.v1';
geometry.frame = 'FRD';
geometry.source_sha256 = wtr_sha256(uint8(signature));
geometry.assumed = struct( ...
    'note', '盒体与舵面为示意网格；铰链/轴来自 SHC09 冻结装配几何，不代表气动实测', ...
    'units', 'm');
geometry.vehicle = struct( ...
    'body_box_m', box, ...
    'duct_outer_m', 0.135, ...
    'duct_inner_m', p.rotor_radius_m, ...
    'vane_limit_rad', p.servo_effective_range_rad, ...
    'hinges_m', g.position_m.', ...
    'axes', g.axis.', ...
    'vane_ids', {{'1', '2', '3', '4', '5', '6'}});
geometry.meshes = struct('body', body, 'vanes', {vanes});
geometry.visual_note = '示意网格，仅用于 WindTrace 显示；不用于气动或结构分析。';

end
