function c = aero_empty_component()
%AERO_EMPTY_COMPONENT 返回组件结构模板（0×0 结构数组）
%
% 字段：
%   name     组件唯一名称
%   kind     'sensor'（读取真值、可带延迟）或 'periodic'（周期更新）
%   period   运行周期（s），必须为正
%   offset   相位偏移（s），满足 0 <= offset < period
%   priority 同一时刻的执行优先级，数值越小越先执行
%   delay    仅 sensor 使用：采样到可用的延迟（s）
%   latches  仅 periodic 使用：是否允许修改 bus.held_command
%   step     periodic 的更新函数句柄 @(t,bus) -> bus
%   sample   sensor 的采样函数句柄 @(t,x) -> 测量值
%
% 字段集中在此定义，避免校验、调度与测试三处结构漂移。

c = struct( ...
    'name', {}, ...
    'kind', {}, ...
    'period', {}, ...
    'offset', {}, ...
    'priority', {}, ...
    'delay', {}, ...
    'latches', {}, ...
    'step', {}, ...
    'sample', {});

end
