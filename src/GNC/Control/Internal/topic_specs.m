function topics = topic_specs()
%TOPIC_SPECS GNC 四级控制器与场景的 Topic 契约集合（唯一定义处）
%
% 输出 topics 为 cell 数组，每项 struct('name',...,'spec',...)：
%   sensor/state              理想传感器测量（13×1：位置/速度/四元数/角速度）
%   navigation/state          IdealState 估计（位置/速度/加速度/四元数/角速度/角加速度）
%   guidance/reference        位置参考（NED）
%   guidance/rate_reference   角速度参考（FRD）
%   control/velocity_setpoint 位置环输出的速度参考（NED）
%   control/attitude_setpoint 速度环输出的姿态与总推力需求
%   control/rate_setpoint     姿态环输出的角速度与角加速度前馈
%   control/torque_setpoint   角速度环输出的机体力矩需求（N·m）
%   control/allocation_status 分配结果与饱和/残差
%   command/computed          内核记录的计算命令
%   command/held              内核记录的锁存命令
%
% 所有载荷均为有限实数结构体；不使用 NaN 表达缺省分量。字段、尺寸、单位
% 和坐标系都在此声明，模块之间不得用未声明结构体传值。

topics = { ...
    entry('sensor/state', aero_topic_spec( ...
        {'value', 'sample_time_s'}, {[13 1], [1 1]}, {'1', 's'}, ...
        struct('description', '理想传感器：[p_n;v_n;q_bn;omega_b]', 'max_age_s', 0.1))), ...
    entry('navigation/state', aero_topic_spec( ...
        {'position', 'velocity', 'acceleration', 'quaternion', 'omega', 'alpha', ...
         'sample_time_s', 'ideal'}, ...
        {[3 1], [3 1], [3 1], [4 1], [3 1], [3 1], [1 1], [1 1]}, ...
        {'m', 'm/s', 'm/s^2', '1', 'rad/s', 'rad/s^2', 's', '1'}, ...
        struct('description', 'IdealState 估计（非 EKF/传感器融合）', 'max_age_s', 0.1))), ...
    entry('guidance/reference', aero_topic_spec( ...
        {'position', 'velocity', 'acceleration', 'yaw', 'yaw_rate'}, ...
        {[3 1], [3 1], [3 1], [1 1], [1 1]}, ...
        {'m', 'm/s', 'm/s^2', 'rad', 'rad/s'}, ...
        struct('description', '位置/速度/加速度参考（NED）', 'max_age_s', 0.2))), ...
    entry('guidance/rate_reference', aero_topic_spec( ...
        {'omega', 'alpha'}, {[3 1], [3 1]}, {'rad/s', 'rad/s^2'}, ...
        struct('description', '角速度/角加速度参考（FRD）', 'max_age_s', 0.2))), ...
    entry('control/velocity_setpoint', aero_topic_spec( ...
        {'velocity', 'acceleration_ff', 'yaw', 'yaw_rate'}, ...
        {[3 1], [3 1], [1 1], [1 1]}, {'m/s', 'm/s^2', 'rad', 'rad/s'}, ...
        struct('description', '位置 P 输出：速度参考、前馈加速度与航向参考（NED）', ...
        'max_age_s', 0.1))), ...
    entry('control/attitude_setpoint', aero_topic_spec( ...
        {'quaternion', 'thrust_n', 'yaw', 'yaw_rate'}, ...
        {[4 1], [1 1], [1 1], [1 1]}, {'1', 'N', 'rad', 'rad/s'}, ...
        struct('description', '速度环输出的姿态、总推力需求与航向速率参考', ...
        'max_age_s', 0.1))), ...
    entry('control/rate_setpoint', aero_topic_spec( ...
        {'omega', 'alpha'}, {[3 1], [3 1]}, {'rad/s', 'rad/s^2'}, ...
        struct('description', '姿态环输出的角速度与角加速度前馈', 'max_age_s', 0.1))), ...
    entry('control/torque_setpoint', aero_topic_spec( ...
        {'torque'}, {[3 1]}, {'N*m'}, ...
        struct('description', '角速度环输出的机体力矩需求（FRD）', 'max_age_s', 0.1))), ...
    entry('control/allocation_status', aero_topic_spec( ...
        {'delta', 'achieved', 'residual', 'saturated', 'motor_rad_s', 've_nominal_m_s'}, ...
        {[6 1], [3 1], [3 1], [3 1], [1 1], [1 1]}, ...
        {'rad', 'N*m', 'N*m', '1', 'rad/s', 'm/s'}, ...
        struct('description', 'PINV 分配结果、相对配平的残差与饱和方向', 'max_age_s', 0.1))), ...
    entry('command/computed', aero_topic_spec( ...
        {'servos', 'motor'}, {[6 1], [1 1]}, {'rad', 'rad/s'}, ...
        struct('description', '内核计算命令（未锁存）', 'max_age_s', 0.1))), ...
    entry('command/held', aero_topic_spec( ...
        {'servos', 'motor'}, {[6 1], [1 1]}, {'rad', 'rad/s'}, ...
        struct('description', '内核锁存命令（进入动力学）', 'max_age_s', 0.1)))};

end

