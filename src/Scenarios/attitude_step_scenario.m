function s = attitude_step_scenario(options)
%ATTITUDE_STEP_SCENARIO 构建 SHC09 独立姿态参考闭环场景
%
% 控制链：
%   Guidance attitude_step → Attitude P → Rate PID → PINV → SHC09
%
% 不装配 Position 或 Velocity；姿态倾斜会产生平动加速度/位置漂移，这是
% 预期物理行为。推力是固定参考，不是推力控制算法。
%
% 选项（全部可选）：
%   aero_source, aero_domain_policy
%   roll_rad / pitch_rad / yaw_rad  阶跃姿态（默认 +5°/0/0）
%   yaw_rate                        世界系偏航角速率（默认 0）
%   thrust_reference_n              固定总推力（默认 trim.thrust_n）
%   start_s/end_s                   姿态阶跃区间（默认 0.5/1.5 s）
%   tspan                           默认 [0,3] s
%   gains/max_records
%
% 输出 s：name/mode/model/cfg；唯一实验定义在 cfg.experiment。

if nargin < 1
    options = struct();
end
options = fill_options(options);

model = shc09_model(struct( ...
    'aero_source', options.aero_source, ...
    'aero_domain_policy', options.aero_domain_policy));

thrust = options.thrust_reference_n;
if isempty(thrust)
    thrust = model.trim.thrust_n;
end
kT0 = model.parameters.duct.k_T0;
omegaRange = model.parameters.motor_device.omega_range_rad_s;
thrustMin = kT0 * omegaRange(1)^2;
thrustMax = kT0 * omegaRange(2)^2;
if ~isscalar(thrust) || ~isfinite(thrust) || thrust < thrustMin - 1e-9 ...
        || thrust > thrustMax + 1e-9
    error('gnc:scenario:thrust', ...
        'thrust_reference_n 必须落在电机实际推力范围 [%.6g, %.6g] N', ...
        thrustMin, thrustMax);
end

cfg = build_config(model, 'attitude', struct( ...
    'tspan', options.tspan, ...
    'roll_rad', options.roll_rad, ...
    'pitch_rad', options.pitch_rad, ...
    'yaw_rad', options.yaw_rad, ...
    'yaw_rate', options.yaw_rate, ...
    'thrust_reference_n', thrust, ...
    'start_s', options.start_s, ...
    'end_s', options.end_s, ...
    'gains', options.gains, ...
    'max_records', options.max_records));

s = struct();
s.name = cfg.experiment.definition.scenario;
s.mode = 'attitude';
s.model = model;
s.cfg = cfg;

end

% ===========================================================================
function options = fill_options(options)
if ~isstruct(options) || ~isscalar(options)
    error('gnc:scenario:options', 'options 必须是标量结构体');
end
defaults = struct( ...
    'aero_source', struct('type', 'external', 'file', '', 'tables', []), ...
    'aero_domain_policy', 'error', ...
    'roll_rad', deg2rad(5), ...
    'pitch_rad', 0, ...
    'yaw_rad', 0, ...
    'yaw_rate', 0, ...
    'thrust_reference_n', [], ...
    'start_s', 0.5, ...
    'end_s', 1.5, ...
    'tspan', [0, 3], ...
    'gains', control_defaults(), ...
    'max_records', 200000);
names = fieldnames(defaults);
for k = 1:numel(names)
    if ~isfield(options, names{k})
        options.(names{k}) = defaults.(names{k});
    end
end

if ~isscalar(options.roll_rad) || ~isscalar(options.pitch_rad) ...
        || ~isscalar(options.yaw_rad) || ~isscalar(options.yaw_rate) ...
        || any(~isfinite([options.roll_rad, options.pitch_rad, ...
            options.yaw_rad, options.yaw_rate]))
    error('gnc:scenario:attitude', 'roll/pitch/yaw/yaw_rate 必须是有限标量');
end
if numel(options.tspan) ~= 2 || any(~isfinite(options.tspan)) ...
        || options.tspan(2) <= options.tspan(1)
    error('gnc:scenario:tspan', 'tspan 必须是有限递增区间');
end
if ~isscalar(options.start_s) || ~isscalar(options.end_s) ...
        || ~isfinite(options.start_s) || ~isfinite(options.end_s)
    error('gnc:scenario:timing', 'start_s/end_s 必须是有限标量');
end
if options.start_s < options.tspan(1) || options.end_s <= options.start_s ...
        || options.end_s > options.tspan(2)
    error('gnc:scenario:timing', ...
        '必须满足 tspan(1) <= start_s < end_s <= tspan(2)');
end
end
