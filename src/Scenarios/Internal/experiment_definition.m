function definition = experiment_definition(model, mode, options)
%EXPERIMENT_DEFINITION 构造本次实验的唯一有效定义（纯值、可序列化）
%
% 该结构只记录实际参与本次实验的模块和参数；不包含函数句柄、路径或
% 输出目录。控制器回调必须从同一 definition 派生，禁止另造一套 gains。

gains = options.gains;
p = model.parameters;
trim = model.trim;
maxThrust = p.duct.k_T0 * p.motor_device.omega_range_rad_s(2)^2;
geometry = shc09_control_surface_geometry(p);

definition = struct();
definition.scenario = '';
definition.method = '';
definition.active_modules = {};
definition.guidance = struct();
definition.navigation = struct();
definition.controllers = struct();
definition.allocation = struct();
definition.rates = gains.rates;

definition.navigation = struct( ...
    'estimator', 'IdealState', ...
    'ideal', true, ...
    'measurement_source', 'sensor/state', ...
    'acceleration_method', 'finite_difference', ...
    'acceleration_limit_m_s2', 50, ...
    'uses_truth_derived_state', true);

if strcmp(mode, 'hover')
    definition.scenario = 'hover_hold';
    definition.method = 'P_PID_P_PID_PINV';
    definition.active_modules = {'guidance', 'position', 'velocity', ...
        'attitude', 'rate', 'allocation'};
    definition.guidance = struct( ...
        'type', 'HoverHold', ...
        'output_topic', 'guidance/reference', ...
        'position_m', options.reference_position(:), ...
        'velocity_m_s', zeros(3, 1), ...
        'acceleration_m_s2', zeros(3, 1), ...
        'yaw_rad', options.yaw, ...
        'yaw_rate_rad_s', options.yaw_rate);
    definition.controllers.position = gains.position;
    definition.controllers.velocity = struct( ...
        'Kp', gains.velocity.Kp, 'Ki', gains.velocity.Ki, ...
        'Kd', gains.velocity.Kd, ...
        'integral_limit', gains.velocity.integral_limit, ...
        'max_thrust_n', maxThrust, ...
        'min_thrust_n', 0.12 * maxThrust, ...
        'horizontal_thrust_margin_n', 0.3 * maxThrust, ...
        'hover_thrust_n', trim.thrust_n, ...
        'max_tilt_rad', gains.max_tilt_rad);
    definition.controllers.attitude = gains.attitude;
    definition.controllers.rate = gains.rate;
elseif strcmp(mode, 'velocity')
    definition.scenario = 'velocity_step';
    definition.method = 'VEL_PID_P_PID_PINV';
    definition.active_modules = {'guidance', 'velocity', 'attitude', ...
        'rate', 'allocation'};
    definition.guidance = struct( ...
        'type', 'VelocityStep', ...
        'output_topic', 'guidance/velocity_reference', ...
        'velocity_reference_ned_m_s', options.velocity_reference(:), ...
        'acceleration_ff_ned_m_s2', options.acceleration_ff(:), ...
        'yaw_rad', options.yaw, ...
        'yaw_rate_rad_s', options.yaw_rate, ...
        'start_s', options.start_s, ...
        'end_s', options.end_s);
    definition.controllers.velocity = struct( ...
        'Kp', gains.velocity.Kp, 'Ki', gains.velocity.Ki, ...
        'Kd', gains.velocity.Kd, ...
        'integral_limit', gains.velocity.integral_limit, ...
        'max_thrust_n', maxThrust, ...
        'min_thrust_n', 0.12 * maxThrust, ...
        'horizontal_thrust_margin_n', 0.3 * maxThrust, ...
        'hover_thrust_n', trim.thrust_n, ...
        'max_tilt_rad', gains.max_tilt_rad);
    definition.controllers.attitude = gains.attitude;
    definition.controllers.rate = gains.rate;
else
    definition.scenario = 'rate_step';
    definition.method = 'RATE_PID_PINV';
    definition.active_modules = {'guidance', 'rate', 'allocation'};
    definition.guidance = struct( ...
        'type', 'BodyRateStep', ...
        'output_topic', 'guidance/rate_reference', ...
        'axis', options.axis, ...
        'amplitude_rad_s', options.amplitude, ...
        'start_s', options.start_s, ...
        'end_s', options.end_s, ...
        'alpha_ff_rad_s2', zeros(3, 1));
    definition.controllers.rate = gains.rate;
end

definition.allocation = struct();
definition.allocation.algorithm = 'PINV';
definition.allocation.B_M = geometry.B_M;
definition.allocation.B_tau = p.servo_torque_coefficient ...
    * trim.exit_speed_m_s^2 * diag([p.l1_m, p.l1_m, p.l2_m]) * geometry.B_M;
definition.allocation.servo_torque_coefficient = p.servo_torque_coefficient;
definition.allocation.l1_m = p.l1_m;
definition.allocation.l2_m = p.l2_m;
definition.allocation.trim_delta_rad = trim.delta_rad;
definition.allocation.delta_limit_rad = p.servo_effective_range_rad;
definition.allocation.ve_min_m_s = gains.allocation.ve_min_m_s;
definition.allocation.hover_thrust_n = trim.thrust_n;
definition.allocation.max_thrust_n = maxThrust;
definition.allocation.min_thrust_n = 0.12 * maxThrust;
definition.allocation.k_T0 = p.duct.k_T0;
definition.allocation.motor_min_rad_s = p.motor_device.omega_range_rad_s(1);
definition.allocation.motor_max_rad_s = p.motor_device.omega_range_rad_s(2);
definition.allocation.motor_model = 'Omega=sqrt(T/k_T0)';
definition.allocation.saturation_tolerance = gains.rate.saturation_tolerance;

end
