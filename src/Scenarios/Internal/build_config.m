function cfg = build_config(model, mode, options)
%BUILD_CONFIG 构造四级 GNC 闭环场景配置（Scenario 内部装配）
%
% 顺序：Scenario Options → Experiment Definition → Controller Parameters
%       → Component Callbacks → 最终配置。
%
% 控制器参数全部从同一个 `definition` 派生，禁止另造一套用于签名的 gains。
% `cfg.experiment` 在最后写入；Simulation 只原样保存。

if nargin < 3
    options = struct();
end
definition = experiment_definition(model, mode, options);
rates = definition.rates;
p = model.parameters;
trim = model.trim;

% ---- Topic 注册 ------------------------------------------------------
cfg = aero_default_config();
cfg.communication.topics = topic_specs();
cfg.communication.command_topic = 'command/computed';
cfg.communication.held_command_topic = 'command/held';
cfg.communication.log.enabled = true;
cfg.communication.log.topics = { ...
    'navigation/state', 'guidance/reference', 'guidance/velocity_reference', ...
    'guidance/attitude_reference', 'guidance/rate_reference', ...
    'control/velocity_setpoint', 'control/attitude_setpoint', ...
    'control/rate_setpoint', 'control/torque_setpoint', ...
    'control/allocation_status', 'command/computed', 'command/held'};
cfg.communication.log.max_records = options.max_records;

% ---- 时间与初值（运行配置，不属于实验定义） --------------------------
cfg.tspan = options.tspan;
cfg.x0 = model.x0;
if strcmp(mode, 'hover') && any(options.position_offset ~= 0)
    cfg.x0(1:3) = cfg.x0(1:3) + options.position_offset(:);
end
cfg.initial_command = model.initial_command;

% ---- 从实验定义派生控制器参数 ---------------------------------------
navParams = struct('sensor_topic', definition.navigation.measurement_source, ...
    'output_topic', 'navigation/state', ...
    'acceleration_limit', definition.navigation.acceleration_limit_m_s2);

a = definition.allocation;
attitudeSourceTopic = 'control/attitude_setpoint';
if strcmp(mode, 'attitude')
    attitudeSourceTopic = definition.guidance.output_topic;
end
allocationParams = struct( ...
    'torque_topic', 'control/torque_setpoint', ...
    'attitude_topic', attitudeSourceTopic, ...
    'status_topic', 'control/allocation_status', ...
    'B_M', a.B_M, ...
    'l1_m', a.l1_m, 'l2_m', a.l2_m, ...
    'servo_torque_coefficient', a.servo_torque_coefficient, ...
    'trim_delta_rad', a.trim_delta_rad, ...
    'delta_limit', a.delta_limit_rad, ...
    'diffuser_ratio', p.diffuser_ratio, ...
    'air_density', p.air_density_kg_m3, ...
    'disc_area', p.disc_area_m2, ...
    'k_T0', a.k_T0, ...
    'hover_thrust_n', a.hover_thrust_n, ...
    'max_thrust_n', a.max_thrust_n, ...
    'motor_min_rad_s', a.motor_min_rad_s, ...
    'motor_max_rad_s', a.motor_max_rad_s, ...
    've_min_m_s', a.ve_min_m_s, ...
    'saturation_tolerance', a.saturation_tolerance);

% ---- 组件表 ----------------------------------------------------------
names = {}; kinds = {}; periods = {}; priorities = {}; delays = {};
latches = {}; topics = {}; steps = {}; samples = {};
layout = shc09_state_layout();

add('sensor_ideal', 'sensor', 1 / rates.sensor_hz, 10, 0.001, false, ...
    'sensor/state', [], @(tt, xx) ideal_sensor_sample(xx, layout));
add('navigation', 'periodic', 1 / rates.navigation_hz, 20, 0, false, '', ...
    @(tt, bb) ideal_state(tt, bb, navParams), []);

if strcmp(mode, 'hover')
    positionParams = struct( ...
        'nav_topic', 'navigation/state', ...
        'reference_topic', 'guidance/reference', ...
        'output_topic', 'control/velocity_setpoint', ...
        'position', definition.controllers.position);

    v = definition.controllers.velocity;
    velocityParams = struct( ...
        'nav_topic', 'navigation/state', ...
        'setpoint_topic', 'control/velocity_setpoint', ...
        'output_topic', 'control/attitude_setpoint', ...
        'velocity', struct('Kp', v.Kp, 'Ki', v.Ki, 'Kd', v.Kd, ...
            'integral_limit', v.integral_limit), ...
        'max_thrust_n', v.max_thrust_n, ...
        'min_thrust_n', v.min_thrust_n, ...
        'horizontal_thrust_margin_n', v.horizontal_thrust_margin_n, ...
        'hover_thrust_n', v.hover_thrust_n, ...
        'max_tilt_rad', v.max_tilt_rad, ...
        'mass_kg', p.mass_kg, 'gravity_m_s2', p.gravity_m_s2, ...
        'rates', rates);

    attitudeParams = struct( ...
        'nav_topic', 'navigation/state', ...
        'attitude_topic', 'control/attitude_setpoint', ...
        'output_topic', 'control/rate_setpoint', ...
        'attitude', definition.controllers.attitude, 'rates', rates);

    guidanceParams = struct('output_topic', definition.guidance.output_topic, ...
        'position', definition.guidance.position_m, ...
        'velocity', definition.guidance.velocity_m_s, ...
        'acceleration', definition.guidance.acceleration_m_s2, ...
        'yaw', definition.guidance.yaw_rad, ...
        'yaw_rate', definition.guidance.yaw_rate_rad_s);
    add('guidance_hover', 'periodic', 1 / rates.guidance_hz, 30, 0, false, '', ...
        @(tt, bb) hover_hold(tt, bb, guidanceParams), []);

    add('position', 'periodic', 1 / rates.position_hz, 40, 0, false, '', ...
        @(tt, bb) position_p(tt, bb, positionParams), []);
    add('velocity', 'periodic', 1 / rates.velocity_hz, 41, 0, false, '', ...
        @(tt, bb) velocity_pid(tt, bb, velocityParams), []);
    add('attitude', 'periodic', 1 / rates.attitude_hz, 50, 0, false, '', ...
        @(tt, bb) attitude_p(tt, bb, attitudeParams), []);
elseif strcmp(mode, 'velocity')
    v = definition.controllers.velocity;
    velocityParams = struct( ...
        'nav_topic', 'navigation/state', ...
        'setpoint_topic', definition.guidance.output_topic, ...
        'output_topic', 'control/attitude_setpoint', ...
        'velocity', struct('Kp', v.Kp, 'Ki', v.Ki, 'Kd', v.Kd, ...
            'integral_limit', v.integral_limit), ...
        'max_thrust_n', v.max_thrust_n, ...
        'min_thrust_n', v.min_thrust_n, ...
        'horizontal_thrust_margin_n', v.horizontal_thrust_margin_n, ...
        'hover_thrust_n', v.hover_thrust_n, ...
        'max_tilt_rad', v.max_tilt_rad, ...
        'mass_kg', p.mass_kg, 'gravity_m_s2', p.gravity_m_s2, ...
        'rates', rates);

    attitudeParams = struct( ...
        'nav_topic', 'navigation/state', ...
        'attitude_topic', 'control/attitude_setpoint', ...
        'output_topic', 'control/rate_setpoint', ...
        'attitude', definition.controllers.attitude, 'rates', rates);

    guidanceParams = struct( ...
        'output_topic', definition.guidance.output_topic, ...
        'velocity', definition.guidance.velocity_reference_ned_m_s, ...
        'acceleration_ff', definition.guidance.acceleration_ff_ned_m_s2, ...
        'yaw', definition.guidance.yaw_rad, ...
        'yaw_rate', definition.guidance.yaw_rate_rad_s, ...
        'start_s', definition.guidance.start_s, ...
        'end_s', definition.guidance.end_s);
    add('guidance_velocity', 'periodic', 1 / rates.guidance_hz, 30, 0, false, '', ...
        @(tt, bb) velocity_step(tt, bb, guidanceParams), []);
    add('velocity', 'periodic', 1 / rates.velocity_hz, 41, 0, false, '', ...
        @(tt, bb) velocity_pid(tt, bb, velocityParams), []);
    add('attitude', 'periodic', 1 / rates.attitude_hz, 50, 0, false, '', ...
        @(tt, bb) attitude_p(tt, bb, attitudeParams), []);
elseif strcmp(mode, 'attitude')
    attitudeParams = struct( ...
        'nav_topic', 'navigation/state', ...
        'attitude_topic', definition.guidance.output_topic, ...
        'output_topic', 'control/rate_setpoint', ...
        'attitude', definition.controllers.attitude, 'rates', rates);
    guidanceParams = struct( ...
        'output_topic', definition.guidance.output_topic, ...
        'quaternion_level', definition.guidance.quaternion_level_bn, ...
        'quaternion_step', definition.guidance.quaternion_bn, ...
        'thrust_n', definition.guidance.thrust_reference_n, ...
        'yaw', definition.guidance.yaw_rad, ...
        'yaw_rate', definition.guidance.yaw_rate_rad_s, ...
        'start_s', definition.guidance.start_s, ...
        'end_s', definition.guidance.end_s);
    add('guidance_attitude', 'periodic', 1 / rates.guidance_hz, 30, 0, false, '', ...
        @(tt, bb) attitude_step(tt, bb, guidanceParams), []);
    add('attitude', 'periodic', 1 / rates.attitude_hz, 50, 0, false, '', ...
        @(tt, bb) attitude_p(tt, bb, attitudeParams), []);
else
    guidanceParams = struct('output_topic', definition.guidance.output_topic, ...
        'axis', definition.guidance.axis, ...
        'amplitude', definition.guidance.amplitude_rad_s, ...
        'start_s', definition.guidance.start_s, ...
        'end_s', definition.guidance.end_s, ...
        'alpha_ff', definition.guidance.alpha_ff_rad_s2);
    add('guidance_rate', 'periodic', 1 / rates.guidance_hz, 30, 0, false, '', ...
        @(tt, bb) body_rate_step(tt, bb, guidanceParams), []);
end

rateParams = struct( ...
    'nav_topic', 'navigation/state', ...
    'rate_topic', 'control/rate_setpoint', ...
    'allocation_topic', 'control/allocation_status', ...
    'output_topic', 'control/torque_setpoint', ...
    'rate', definition.controllers.rate, 'rates', rates);
if strcmp(mode, 'rate')
    rateParams.rate_topic = 'guidance/rate_reference';
end
add('rate', 'periodic', 1 / rates.rate_hz, 60, 0, false, '', ...
    @(tt, bb) rate_pid(tt, bb, rateParams), []);
add('allocation', 'periodic', 1 / rates.rate_hz, 70, 0, false, '', ...
    @(tt, bb) pinv_allocator(tt, bb, allocationParams), []);
add('latch_servos', 'periodic', 1 / rates.servo_latch_hz, 80, 0, true, '', ...
    @latch_servos, []);
add('latch_motor', 'periodic', 1 / rates.motor_latch_hz, 90, 0, true, '', ...
    @latch_motor, []);

cfg.components = struct('name', names, 'kind', kinds, 'period', periods, ...
    'priority', priorities, 'delay', delays, 'latches', latches, ...
    'topic', topics, 'step', steps, 'sample', samples);

% ---- 最终运行配置与唯一实验定义 -------------------------------------
cfg = aero_validate_config(cfg);
definition.components = aero_experiment_components(cfg.components);
definitionPayload = struct('schema', 'aero-experiment-definition/1', ...
    'definition', definition);
definitionHash = aero_sha256_text(aero_canonical_json(definitionPayload));
experiment = struct();
experiment.schema = 'aero-experiment-definition/1';
experiment.definition = definition;
experiment.definition_sha256 = definitionHash;
cfg.experiment = experiment;
identity = aero_experiment_identity(experiment, cfg, model.metadata, ...
    definition.components);
cfg.experiment.identity_sha256 = identity.input_signature_sha256;

    function add(name, kind, period, priority, delay, latch, topic, step, sample)
        names{end + 1} = name; %#ok<AGROW>
        kinds{end + 1} = kind; %#ok<AGROW>
        periods{end + 1} = period; %#ok<AGROW>
        priorities{end + 1} = priority; %#ok<AGROW>
        delays{end + 1} = delay; %#ok<AGROW>
        latches{end + 1} = latch; %#ok<AGROW>
        topics{end + 1} = topic; %#ok<AGROW>
        steps{end + 1} = step; %#ok<AGROW>
        samples{end + 1} = sample; %#ok<AGROW>
    end
end
