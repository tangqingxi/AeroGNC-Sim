function cfg = build_config(model, mode, options)
%BUILD_CONFIG 构造四级 GNC 闭环场景配置（Scenario 内部装配）
%
% 输入：
%   model   - SHC09 模型（hover 初态）
%   mode    - 'hover'（Position→Velocity→Attitude→Rate）或 'rate'（Rate alone）
%   options - tspan、reference/step、offset、gains、max_records
%
% 输出：
%   cfg - aero_default_config 扩展：Topic 契约、独立频率的控制器组件、
%         command/held 记录 Topic 与有界发布日志。
%
% 本文件只做装配，不包含控制律；四级控制器位于 src/GNC/Control 的独立目录。

if nargin < 3
    options = struct();
end
gains = options.gains;
rates = gains.rates;
p = model.parameters;

% ---- Topic 注册 ------------------------------------------------------
cfg = aero_default_config();
cfg.communication.topics = topic_specs();
cfg.communication.command_topic = 'command/computed';
cfg.communication.held_command_topic = 'command/held';
cfg.communication.log.enabled = true;
cfg.communication.log.topics = { ...
    'navigation/state', 'guidance/reference', 'guidance/rate_reference', ...
    'control/velocity_setpoint', 'control/attitude_setpoint', ...
    'control/rate_setpoint', 'control/torque_setpoint', ...
    'control/allocation_status', 'command/computed', 'command/held'};
cfg.communication.log.max_records = options.max_records;

% ---- 时间与初值 ------------------------------------------------------
cfg.tspan = options.tspan;
cfg.x0 = model.x0;
if strcmp(mode, 'hover') && any(options.position_offset ~= 0)
    cfg.x0(1:3) = cfg.x0(1:3) + options.position_offset(:);
end
cfg.initial_command = model.initial_command;

% ---- 共享参数 --------------------------------------------------------
trim = model.trim;
rateTopic = 'control/rate_setpoint';
if strcmp(mode, 'rate')
    rateTopic = 'guidance/rate_reference';
end

navParams = struct('sensor_topic', 'sensor/state', ...
    'output_topic', 'navigation/state', 'acceleration_limit', 50);

positionParams = struct( ...
    'nav_topic', 'navigation/state', ...
    'reference_topic', 'guidance/reference', ...
    'output_topic', 'control/velocity_setpoint', ...
    'position', gains.position);

maxThrust = p.duct.k_T0 * p.motor_device.omega_range_rad_s(2)^2;
velocityParams = struct( ...
    'nav_topic', 'navigation/state', ...
    'setpoint_topic', 'control/velocity_setpoint', ...
    'output_topic', 'control/attitude_setpoint', ...
    'velocity', gains.velocity, ...
    'max_thrust_n', maxThrust, ...
    'min_thrust_n', 0.12 * maxThrust, ...
    'horizontal_thrust_margin_n', 0.3 * maxThrust, ...
    'hover_thrust_n', trim.thrust_n, ...
    'max_tilt_rad', gains.max_tilt_rad, ...
    'mass_kg', p.mass_kg, 'gravity_m_s2', p.gravity_m_s2, ...
    'rates', rates);

attitudeParams = struct( ...
    'nav_topic', 'navigation/state', ...
    'attitude_topic', 'control/attitude_setpoint', ...
    'output_topic', 'control/rate_setpoint', ...
    'attitude', gains.attitude, 'rates', rates);

rateParams = struct( ...
    'nav_topic', 'navigation/state', ...
    'rate_topic', rateTopic, ...
    'allocation_topic', 'control/allocation_status', ...
    'output_topic', 'control/torque_setpoint', ...
    'rate', gains.rate, 'rates', rates);

allocationParams = struct( ...
    'torque_topic', 'control/torque_setpoint', ...
    'attitude_topic', 'control/attitude_setpoint', ...
    'status_topic', 'control/allocation_status', ...
    'B_M', shc09_control_surface_geometry(p).B_M, ...
    'l1_m', p.l1_m, 'l2_m', p.l2_m, ...
    'servo_torque_coefficient', p.servo_torque_coefficient, ...
    'trim_delta_rad', trim.delta_rad, ...
    'delta_limit', p.servo_effective_range_rad, ...
    'diffuser_ratio', p.diffuser_ratio, ...
    'air_density', p.air_density_kg_m3, ...
    'disc_area', p.disc_area_m2, ...
    'k_T0', p.duct.k_T0, ...
    'hover_thrust_n', trim.thrust_n, ...
    'max_thrust_n', p.duct.k_T0 * p.motor_device.omega_range_rad_s(2)^2, ...
    'motor_min_rad_s', p.motor_device.omega_range_rad_s(1), ...
    'motor_max_rad_s', p.motor_device.omega_range_rad_s(2), ...
    've_min_m_s', gains.allocation.ve_min_m_s, ...
    'saturation_tolerance', gains.rate.saturation_tolerance);

% ---- 组件表 ----------------------------------------------------------
names = {}; kinds = {}; periods = {}; priorities = {}; delays = {};
latches = {}; topics = {}; steps = {}; samples = {};
layout = shc09_state_layout();

add('sensor_ideal', 'sensor', 1 / rates.sensor_hz, 10, 0.001, false, ...
    'sensor/state', [], @(tt, xx) ideal_sensor_sample(xx, layout));
add('navigation', 'periodic', 1 / rates.navigation_hz, 20, 0, false, '', ...
    @(tt, bb) ideal_state(tt, bb, navParams), []);

if strcmp(mode, 'hover')
    guidanceParams = struct('output_topic', 'guidance/reference', ...
        'position', options.reference_position(:), ...
        'velocity', zeros(3, 1), 'acceleration', zeros(3, 1), ...
        'yaw', options.yaw, 'yaw_rate', options.yaw_rate);
    add('guidance_hover', 'periodic', 1 / rates.guidance_hz, 30, 0, false, '', ...
        @(tt, bb) hover_hold(tt, bb, guidanceParams), []);

    add('position', 'periodic', 1 / rates.position_hz, 40, 0, false, '', ...
        @(tt, bb) position_p(tt, bb, positionParams), []);
    add('velocity', 'periodic', 1 / rates.velocity_hz, 41, 0, false, '', ...
        @(tt, bb) velocity_pid(tt, bb, velocityParams), []);
    add('attitude', 'periodic', 1 / rates.attitude_hz, 50, 0, false, '', ...
        @(tt, bb) attitude_p(tt, bb, attitudeParams), []);
else
    guidanceParams = struct('output_topic', 'guidance/rate_reference', ...
        'axis', options.axis, 'amplitude', options.amplitude, ...
        'start_s', options.start_s, 'end_s', options.end_s, ...
        'alpha_ff', zeros(3, 1));
    add('guidance_rate', 'periodic', 1 / rates.guidance_hz, 30, 0, false, '', ...
        @(tt, bb) body_rate_step(tt, bb, guidanceParams), []);
end

add('rate', 'periodic', 1 / rates.rate_hz, 60, 0, false, '', ...
    @(tt, bb) rate_pid(tt, bb, rateParams), []);
add('allocation', 'periodic', 1 / rates.rate_hz, 70, 0, false, '', ...
    @(tt, bb) pinv_allocator(tt, bb, allocationParams), []);
add('latch_servos', 'periodic', 1 / rates.servo_latch_hz, 80, 0, true, '', ...
    @latch_servos, []);
add('latch_motor', 'periodic', 1 / rates.motor_latch_hz, 90, 0, true, '', ...
    @latch_motor, []);

cfg.components = struct('name', names, 'kind', kinds, 'period', periods, ...
    'priority', priorities, 'delay', delays, 'latches', latches, ...
    'topic', topics, 'step', steps, 'sample', samples);

    function add(name, kind, period, priority, delay, latch, topic, step, sample)
        names{end + 1} = name; %#ok<AGROW>
        kinds{end + 1} = kind; %#ok<AGROW>
        periods{end + 1} = period; %#ok<AGROW>
        priorities{end + 1} = priority; %#ok<AGROW>
        delays{end + 1} = delay; %#ok<AGROW>
        latches{end + 1} = latch; %#ok<AGROW>
        topics{end + 1} = topic; %#ok<AGROW>
        steps{end + 1} = step; %#ok<AGROW>
        samples{end + 1} = sample; %#ok<AGROW>
    end
end
